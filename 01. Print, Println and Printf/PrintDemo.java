// Demonstration of System.out.print() to Display Fruits on the Same Line

// Program Start

// Main Class Declaration

public class PrintDemo
{
    // Main Method Declaration

    public static void main(String[] args)
    {
        // Calls to the print() Method

        System.out.print("Some examples of fruits are ");
        System.out.print("Orange, ");
        System.out.print("Watermelon, ");
        System.out.print("Grapes, ");
        System.out.print("Pineapple and ");
        System.out.print("Strawberry.");
    }

    // End of Main Method

}

// End of Main Class

// End of Program
